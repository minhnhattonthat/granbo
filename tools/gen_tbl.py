    "ニヌネノハバパヒビピフブプヘベペホボポマミムメモヤユヨラリルレロワヲンァィゥェォッャュョ"
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    "ー～、・〈〉”“！？○△。＋－×÷／＝▼￥（）「」『』語半元小中"
    "大内外上下左右前後先高低入出東西南北今昔新古弱強始終年日多少遠近"
    "良悪無早明暗売買速移読会知第一二歩皮効言見行住食話飛閉▶書使思作"
