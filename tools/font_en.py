ADVANCE = {" ": 3, "「": 0}


def width(ch):
    return max(len(r) for r in ART[ch])


def advance(ch):
    return ADVANCE.get(ch, width(ch) + 1)


def pixels(ch):
    """16 rows x 8 palette indices."""
    rows = [[3] * 8 for _ in range(16)]
    for y, r in enumerate(ART[ch]):
        for x, c in enumerate(r):
            rows[TOP + y][x] = {"#": 1, "+": 2, ".": 3}[c]
    return rows


def glyph_bytes(ch):
    px = pixels(ch)
    out = bytearray()
    for half in (0, 8):
        for y in range(half, half + 8):
            for x in range(0, 8, 2):
                out.append(px[y][x] | px[y][x + 1] << 4)
    return bytes(out)


def _check():
    for ch, rows in ART.items():
        assert width(ch) <= 7, ch  # 1 px gap must fit in the 8 px cell for monospace menus
        assert len(rows) <= 11, ch
        assert all(set(r) <= set("#+.") for r in rows), ch
        assert len(glyph_bytes(ch)) == 0x40


_check()
