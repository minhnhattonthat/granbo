def width(ch):
    return max(len(r) for r in ART[ch])


def advance(ch):
    return width(ch) + 1


def tile(ch):
    px = [[3] * 8 for _ in range(8)]
    for y, r in enumerate(ART[ch]):
        for x, c in enumerate(r):
            px[TOP + y][x] = {"#": 1, ".": 3}[c]
    return bytes(px[y][x] | px[y][x + 1] << 4 for y in range(8) for x in range(0, 8, 2))


def tiles(codes):
    out = bytearray(tile(" ") * 256)
    for ch, code in codes.items():
        if ch in ART and code < 256:
            out[code * 32:code * 32 + 32] = tile(ch)
    return bytes(out)


def advances(codes):
    out = bytearray([advance(" ")] * 256)
    for ch, code in codes.items():
        if ch in ART and code < 256:
            out[code] = advance(ch)
    return bytes(out)


def _check():
    for ch, rows in ART.items():
        assert width(ch) <= 7 and len(rows) <= 8 - TOP, ch
        assert all(set(r) <= set("#.") for r in rows), ch


_check()
